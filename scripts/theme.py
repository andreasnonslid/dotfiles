# ---------------------------------------------------------------- data

def names(kind):
    return sorted(p.stem for p in (PALETTE / kind).glob("*.toml"))


def load(kind, name):
    p = PALETTE / kind / f"{name}.toml"
    if not p.exists():
        sys.exit(f"no {kind[:-1]} {name!r}; have: {', '.join(names(kind))}")
    return tomllib.loads(p.read_text())


def current(kind):
    p = PALETTE / f"current-{kind}"
    n = p.read_text().strip() if p.exists() else ""
    return n if n in names(kind) else names(kind)[0]


def pick_menu(kind, verb):
    """One submenu entry per name, key = first letter not yet used."""
    used, kids = set(), []
    for n in names(kind):
        key = next(ch for ch in n if ch.isalpha() and ch not in used)
        used.add(key)
        kids.append((key, n, f"{ME} {verb} {n}"))
    return kids


