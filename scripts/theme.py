def yaml_menu(items, ind):
    out = []
    for k, d, c in items:
        pad = "  " * ind
        out.append(f'{pad}- key: "{k}"')
        out.append(f'{pad}  desc: "{d}"')
        if isinstance(c, list):
            out.append(f"{pad}  submenu:")
            out += yaml_menu(c, ind + 2)
        else:
            out.append(f'{pad}  cmd: "{c}"')
    return out


def r_whichkey(t):
    items = menu(t)
    head = f"""# GENERATED by scripts/theme.py. Do not edit; change menu() there.
font: {FONT} 15
background: "{t['bg']}f2"
color: "{t['fg']}"
border: "{t['accent']}"
separator: "  ➜  "
border_width: 3
corner_r: 16
padding: 22
rows_per_column: 9
column_padding: 40
anchor: center
menu:
"""
    return {"which-key/.config/wlr-which-key/config.yaml": head + "\n".join(yaml_menu(items, 1)) + "\n"}


