# ---------------------------------------------------------------- wallpaper

def png(path, w, h, rows):
    def chunk(tag, data):
        b = struct.pack(">I", len(data)) + tag + data
        return b + struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF)
    raw = b"".join(b"\x00" + bytes(r) for r in rows)
    path.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile(dir=path.parent, delete=False) as f:
        f.write(b"\x89PNG\r\n\x1a\n")
        f.write(chunk(b"IHDR", struct.pack(">IIBBBBB", w, h, 8, 2, 0, 0, 0)))
        f.write(chunk(b"IDAT", zlib.compress(raw, 6)))
        f.write(chunk(b"IEND", b""))
    os.replace(f.name, path)


def wallpaper(c, kind, w=1280, h=720):
    """kind: flat | glow (two soft glows + ring) | rings (concentric rings)."""
    bg, a1, a2 = rgb(c["bg"]), rgb(c["accent"]), rgb(c["accent2"])
    lo = tuple(int(v * 0.55) for v in bg)
    hi = tuple(min(255, int(v * 1.25) + 6) for v in bg)
    glows = [((0.15, 0.9), 0.65, a1, 0.34), ((0.88, 0.12), 0.55, a2, 0.28)]
    asp = w / h
    rows = []
    for y in range(h):
        row = bytearray()
        fy = y / h
        for x in range(w):
            fx = x / w
            if kind == "flat":
                px = list(bg)
            else:
                u = fx * 0.5 + fy * 0.5
                px = [hi[i] + (lo[i] - hi[i]) * u for i in range(3)]
            if kind == "glow":
                for (cx, cy), r, col, st in glows:
                    d = math.hypot((fx - cx) * asp, fy - cy) / r
                    if d < 1:
                        k = (1 - d) ** 2 * st
                        for i in range(3):
                            px[i] += (col[i] - px[i]) * k
                d = math.hypot((fx - 0.15) * asp, fy - 0.9)
                ring = max(0.0, 1 - abs(d - 0.45) / 0.004) * 0.10
                for i in range(3):
                    px[i] += (a1[i] - px[i]) * ring
            elif kind == "rings":
                d = math.hypot((fx - 0.5) * asp, fy - 0.5)
                for n in range(1, 9):
                    ring = max(0.0, 1 - abs(d - n * 0.12) / 0.004) * (0.22 - n * 0.02)
                    col = a1 if n % 2 else a2
                    for i in range(3):
                        px[i] += (col[i] - px[i]) * ring
            row += bytes(int(min(255, max(0, v))) for v in px)
        rows.append(row)
    png(WALLPAPER, w, h, rows)


# ---------------------------------------------------------------- main

def sh(*cmd):
    try:
        subprocess.run(cmd, check=False, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    except FileNotFoundError:
        pass


def apply(colors, style, reload=True):
    c, s = load("colors", colors), load("styles", style)
    for r in RENDERERS:
        for rel, text in r(c, s).items():
            dst = (PARTS / rel).resolve()
            dst.parent.mkdir(parents=True, exist_ok=True)
            dst.write_text(text)
    (PALETTE / "current-colors").write_text(colors + "\n")
    (PALETTE / "current-styles").write_text(style + "\n")
    wallpaper(c, s["wallpaper"])
    if reload:
        sh("swaymsg", "reload")
        sh("pkill", "-SIGUSR2", "-x", "waybar")
        sh("makoctl", "reload")
    print(f"colors: {colors}  style: {style}")


def cycle(kind):
    ns = names(kind)
    return ns[(ns.index(current(kind)) + 1) % len(ns)]


def main(argv):
    cmd, args = (argv[1] if len(argv) > 1 else "current"), argv[2:]
    cc, cs = current("colors"), current("styles")
    if cmd == "list" and args[:1] in (["colors"], ["styles"]):
        print("\n".join(names(args[0])))
    elif cmd == "current":
        print(f"colors: {cc}  style: {cs}")
    elif cmd == "colors" and args:
        apply(args[0], cs)
    elif cmd == "style" and args:
        apply(cc, args[0])
    elif cmd == "apply" and args:
        apply(args[0], args[1] if len(args) > 1 else cs)
    elif cmd == "next-colors":
        apply(cycle("colors"), cs)
    elif cmd == "next-style":
        apply(cc, cycle("styles"))
    elif cmd == "random":
        apply(random.choice(names("colors")), random.choice(names("styles")))
    else:
        sys.exit(__doc__)


if __name__ == "__main__":
    main(sys.argv)
