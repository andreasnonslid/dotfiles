PARTS = ROOT / "parts"
PALETTE = PARTS / "palette/.config/palette"
WALLPAPER = Path.home() / ".local/share/palette/wallpaper.png"
FONT = "IosevkaTerm Nerd Font"

# Nerd Font (Font Awesome range) glyphs for the leader menu.
I = {
    "left": "", "down": "", "up": "", "right": "",
    "ws": "", "move": "", "full": "", "close": "",
    "layout": "", "resize": "", "apps": "", "term": "",
    "search": "", "kbd": "", "lock": "", "out": "",
    "sleep": "", "reboot": "", "off": "", "theme": "",
    "bar": "", "shot": "",
}

SWAY = "swaymsg "


def theme_menu():
    used, kids = set(), []
    for n in themes():
        key = next(ch for ch in n if ch.isalpha() and ch not in used)
        used.add(key)
        kids.append((key, n, f"{ROOT}/scripts/theme.py apply {n}"))
    return kids


def menu(t):
    """(key, desc, cmd) or (key, desc, [children]) -- single source for which-key."""
    m = []
    for k, d in [("h", "left"), ("j", "down"), ("k", "up"), ("l", "right")]:
        m.append((k, f"{I[d]}  Focus {d}", SWAY + f"focus {d}"))
    for k, d in [("H", "left"), ("J", "down"), ("K", "up"), ("L", "right")]:
        m.append((k, f"{I['move']}  Move {d}", SWAY + f"move {d}"))
    for n in range(1, 10):
        m.append((str(n), f"{I['ws']}  Workspace {n}", SWAY + f"workspace number {n}"))
    m += [
        ("f", f"{I['full']}  Fullscreen", SWAY + "fullscreen toggle"),
        ("x", f"{I['close']}  Close window", SWAY + "kill"),
        ("r", f"{I['resize']}  Resize mode", SWAY + "mode resize"),
        ("o", f"{I['kbd']}  On-screen keyboard", "~/.config/sway/osk-toggle.sh"),
        ("m", f"{I['move']}  Move to workspace",
         [(str(n), f"To {n}", SWAY + f"move container to workspace number {n}") for n in range(1, 10)]),
        ("t", f"{I['layout']}  Layout", [
            ("s", "Stacking", SWAY + "layout stacking"),
            ("w", "Tabbed", SWAY + "layout tabbed"),
            ("e", "Split toggle", SWAY + "layout toggle split"),
            ("v", "Split vertical", SWAY + "splitv"),
            ("b", "Split horizontal", SWAY + "splith"),
        ]),
        ("a", f"{I['apps']}  Apps", [
            ("t", f"{I['term']}  Terminal", "alacritty"),
            ("d", f"{I['search']}  Launcher", "fuzzel"),
        ]),
        ("z", f"{I['theme']}  Theme", theme_menu()),
        ("q", f"{I['off']}  Session", [
            ("l", f"{I['lock']}  Lock", f"swaylock -f -c {t['bg'].lstrip('#')}"),
            ("e", f"{I['out']}  Log out", SWAY + "exit"),
            ("s", f"{I['sleep']}  Suspend", "systemctl suspend"),
            ("r", f"{I['reboot']}  Reboot", "systemctl reboot"),
            ("p", f"{I['off']}  Power off", "systemctl poweroff"),
        ]),
    ]
    return m


def themes():
    return sorted(p.stem for p in (PALETTE / "themes").glob("*.toml"))


# ---------------------------------------------------------------- renderers

def rgb(c):
    c = c.lstrip("#")
    return tuple(int(c[i:i + 2], 16) for i in (0, 2, 4))


def r_sway(t):
    lines = ["# GENERATED by scripts/theme.py from parts/palette themes. Do not edit.\n"]
    for k in ("bg", "fg", "dim", "accent", "accent2", "warn", "urgent"):
        lines.append(f"set ${k} {t[k]}\n")
    lines.append(f"set $bgrgb {t['bg'].lstrip('#')}\n")
    lines.append("output * bg ~/.local/share/palette/wallpaper.png fill\n")
    return {"sway/.config/sway/colors.conf": "".join(lines)}


def r_waybar(t):
    s = "/* GENERATED by scripts/theme.py. Do not edit. */\n"
    for k in ("bg", "fg", "dim", "accent", "accent2", "warn", "urgent"):
        s += f"@define-color {k} {t[k]};\n"
    return {"waybar/.config/waybar/colors.css": s}


def r_alacritty(t):
    a = t["ansi"]
    names = ["black", "red", "green", "yellow", "blue", "magenta", "cyan", "white"]
    s = "# GENERATED by scripts/theme.py. Do not edit.\n"
    s += f'[colors.primary]\nbackground = "{t["bg"]}"\nforeground = "{t["fg"]}"\n\n'
    s += f'[colors.cursor]\ncursor = "{t["accent"]}"\ntext = "{t["bg"]}"\n\n'
    s += f'[colors.selection]\nbackground = "{t["accent"]}"\ntext = "{t["bg"]}"\n\n'
    for sect in ("normal", "bright"):
        s += f"[colors.{sect}]\n"
        for n, c in zip(names, a):
            s += f'{n} = "{c}"\n'
        s += "\n"
    return {"alacritty/.config/alacritty/colors.toml": s}


