#!/usr/bin/env python3
"""Theme generator: one palette -> every part's colors (+ a generated wallpaper).

  theme.py list | current | apply NAME | next

Source of truth: parts/palette/.config/palette/themes/NAME.toml (+ `current`).
Outputs are written into the parts (committed) so the symlinks just work:
  sway/colors.conf  waybar/colors.css  alacritty/colors.toml  fuzzel/fuzzel.ini
  which-key/config.yaml  hammerspoon/colors.lua  bashrc/.config/mako/config
The wallpaper is rendered to ~/.local/share/palette/wallpaper.png (not committed).
"""
