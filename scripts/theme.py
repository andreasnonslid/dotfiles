def yaml_menu(items, ind):
    out = []
    for k, d, cmd in items:
        pad = "  " * ind
        out += [f'{pad}- key: "{k}"', f'{pad}  desc: "{d}"']
        if isinstance(cmd, list):
            out.append(f"{pad}  submenu:")
            out += yaml_menu(cmd, ind + 2)
        else:
            out.append(f'{pad}  cmd: "{cmd}"')
    return out


