def r_hammerspoon(t):
    s = "-- GENERATED by scripts/theme.py. Do not edit.\nreturn {\n"
    for k in ("bg", "fg", "dim", "accent", "accent2", "warn", "urgent"):
        s += f'  {k} = "{t[k]}",\n'
    return {"hammerspoon/.hammerspoon/colors.lua": s + "}\n"}


RENDERERS = [r_sway, r_waybar, r_alacritty, r_fuzzel, r_whichkey, r_mako, r_hammerspoon]


# ---------------------------------------------------------------- wallpaper

def png(path, w, h, rows):
    def chunk(tag, data):
        c = struct.pack(">I", len(data)) + tag + data
        return c + struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF)
    raw = b"".join(b"\x00" + bytes(r) for r in rows)
    path.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile(dir=path.parent, delete=False) as f:
        f.write(b"\x89PNG\r\n\x1a\n")
        f.write(chunk(b"IHDR", struct.pack(">IIBBBBB", w, h, 8, 2, 0, 0, 0)))
        f.write(chunk(b"IDAT", zlib.compress(raw, 6)))
        f.write(chunk(b"IEND", b""))
    os.replace(f.name, path)


def wallpaper(t, w=1280, h=720):
    """Diagonal gradient + two soft glows (accent, accent2) + a faint ring."""
    bg, a1, a2 = rgb(t["bg"]), rgb(t["accent"]), rgb(t["accent2"])
    lo = tuple(int(c * 0.55) for c in bg)
    hi = tuple(min(255, int(c * 1.25) + 6) for c in bg)
    glows = [((0.15, 0.9), 0.65, a1, 0.34), ((0.88, 0.12), 0.55, a2, 0.28)]
    rows = []
    for y in range(h):
        row = bytearray()
        for x in range(w):
            u = (x / w * 0.5 + y / h * 0.5)
            px = [hi[i] + (lo[i] - hi[i]) * u for i in range(3)]
            for (cx, cy), r, col, s in glows:
                dx, dy = (x / w - cx) * (w / h), y / h - cy
                d = math.sqrt(dx * dx + dy * dy) / r
                if d < 1:
                    k = (1 - d) ** 2 * s
                    for i in range(3):
                        px[i] += (col[i] - px[i]) * k
            # faint ring around the first glow
            d = math.hypot((x / w - 0.15) * (w / h), y / h - 0.9)
            ring = max(0.0, 1 - abs(d - 0.45) / 0.004) * 0.10
            for i in range(3):
                px[i] += (a1[i] - px[i]) * ring
            row += bytes(int(min(255, max(0, v))) for v in px)
        rows.append(row)
    png(WALLPAPER, w, h, rows)


# ---------------------------------------------------------------- main

def load(name):
    p = PALETTE / "themes" / f"{name}.toml"
    if not p.exists():
        sys.exit(f"no theme {name!r}; have: {', '.join(themes())}")
    return tomllib.loads(p.read_text())


def current():
    p = PALETTE / "current"
    return p.read_text().strip() if p.exists() else themes()[0]


def sh(*cmd):
    try:
        subprocess.run(cmd, check=False, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    except FileNotFoundError:
        pass


def apply(name, reload=True):
    t = load(name)
    for r in RENDERERS:
        for rel, text in r(t).items():
            dst = (PARTS / rel).resolve()
            dst.parent.mkdir(parents=True, exist_ok=True)
            dst.write_text(text)
    (PALETTE / "current").write_text(name + "\n")
    wallpaper(t)
    if reload:
        sh("swaymsg", "reload")
        sh("pkill", "-SIGUSR2", "-x", "waybar")
        sh("makoctl", "reload")
    print(f"theme: {name}")


def main(argv):
    cmd = argv[1] if len(argv) > 1 else "current"
    if cmd == "list":
        print("\n".join(themes()))
    elif cmd == "current":
        print(current())
    elif cmd == "apply" and len(argv) > 2:
        apply(argv[2])
    elif cmd == "next":
        ts = themes()
        apply(ts[(ts.index(current()) + 1) % len(ts)])
    elif cmd == "random":
        apply(random.choice(themes()))
    else:
        sys.exit(__doc__)


if __name__ == "__main__":
    main(sys.argv)
