#!/usr/bin/env python3
"""Grow the login quote list from the fortune-mod data files (apt: fortunes).

Keeps only entries that look like real quotes: short, attributed, single-paragraph, no coarse words.
The hand-curated lines at the top of quotes.txt are never touched; everything below the marker is
regenerated.   Usage: scripts/build-quotes.py [--dry]
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "parts/sway/.config/sway/quotes.txt"
MARK = "# --- generated by scripts/build-quotes.py (do not edit below) ---"
DIRS = [Path("/usr/share/games/fortunes"), Path("/usr/share/fortune")]
FILES = ["wisdom", "literature", "art", "science", "tao", "fortunes"]  # in order of preference
MAXLEN, MINLEN = 150, 30
COARSE = re.compile(
    r"\b(sex|sexual|drunk|beer|whisky|vodka|fuck|shit|damn|hell|ass|bitch|piss|pregnan|nude|naked|kill|"
    r"die|dead|death|murder|suicide|drug|cocaine|rape|slave|nazi|hitler|jew|christ|god|jesus|church|"
    r"women|woman|men|wife|husband|lawyer|politic|republican|democrat|tax|money|rich|poor)\b", re.I)
ATTRIB = re.compile(r"\s*(?:\n\s*)?[-–—]{1,2}\s*([A-Z][^\n]{2,60}?)\s*$")


def entries():
    for d in DIRS:
        for name in FILES:
            p = d / name
            if p.is_file():
                text = p.read_text(errors="ignore")
                for raw in text.split("\n%\n"):
                    yield name, raw.strip("\n")


def main(dry=False):
    seen, out = set(), []
    for _name, raw in entries():
        m = ATTRIB.search(raw)
        if not m:
            continue
        author = re.sub(r"\s+", " ", m[1]).strip(" ,.;")
        body = re.sub(r"\s+", " ", raw[: m.start()]).strip()
        body = body.strip('"“”\' ')
        if not (MINLEN <= len(body) <= MAXLEN) or "\n" in raw[: m.start()].strip("\n\t ").replace("\n\t", ""):
            pass
        if not (MINLEN <= len(body) <= MAXLEN):
            continue
        if COARSE.search(body) or COARSE.search(author) or "|" in body or "|" in author:
            continue
        if len(author.split()) > 6 or re.search(r"\d{3,}", author):
            continue
        key = body.lower()
        if key in seen:
            continue
        seen.add(key)
        out.append((body, author))
    out.sort()
    print(f"{len(out)} quotes pass the filters (from {sum(1 for _ in entries())} fortune entries)")
    if dry or not out:
        for b, a in out[:12]:
            print(f"  “{b}” — {a}")
        return
    head = OUT.read_text().split(MARK)[0].rstrip("\n") + "\n"
    OUT.write_text(head + MARK + "\n" + "".join(f"{b}|{a}\n" for b, a in out))
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main("--dry" in sys.argv)
