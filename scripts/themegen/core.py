def names(kind):
    return sorted(p.stem for p in (PALETTE / kind).glob("*.toml"))


def load(kind, name):
    p = PALETTE / kind / f"{name}.toml"
    if not p.exists():
        sys.exit(f"no {kind[:-1]} {name!r}; have: {', '.join(names(kind))}")
    return tomllib.loads(p.read_text())


def current(kind):
    p = PALETTE / f"current-{kind}"
    n = p.read_text().strip() if p.exists() else ""
    return n if n in names(kind) else names(kind)[0]


def rgb(c):
    c = c.lstrip("#")
    return tuple(int(c[i:i + 2], 16) for i in (0, 2, 4))


def mix(a, b, t):
    ra, rb = rgb(a), rgb(b)
    return "#%02x%02x%02x" % tuple(round(ra[i] + (rb[i] - ra[i]) * t) for i in range(3))


def hue_of(hexc):
    r, g, b = (v / 255 for v in rgb(hexc))
    h, sat, v = colorsys.rgb_to_hsv(r, g, b)
    return h * 360, sat, v


def nearest(table, hexc):
    h, sat, _ = hue_of(hexc)
    if sat < 0.15:
        return "slate" if table is GNOME_ACCENTS else "grey"
    return min(table, key=lambda t: min(abs(h - t[1]), 360 - abs(h - t[1])))[0]


